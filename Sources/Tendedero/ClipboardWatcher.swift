import AppKit

/// Opt-in clipboard observation. File references take precedence over an app's icon/image representations.
@MainActor
final class ClipboardWatcher {
    private let onRecord: (ClipboardRecord) -> Void
    private let onError: (String) -> Void
    private var timer: Timer?
    private var lastCount = 0
    private var generation = UUID()
    private let pasteboard: NSPasteboard

    static let ownCopyType = NSPasteboard.PasteboardType("local.suiqu.copied")
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"), ownCopyType,
    ]
    static var isEnabled: Bool {
        get { AppSettings.defaults.bool(forKey: "clipboardEnabled") }
        set { AppSettings.defaults.set(newValue, forKey: "clipboardEnabled") }
    }

    init(pasteboard: NSPasteboard = .general, onRecord: @escaping (ClipboardRecord) -> Void,
         onError: @escaping (String) -> Void = { _ in }) {
        self.pasteboard = pasteboard
        self.onRecord = onRecord
        self.onError = onError
    }

    func start() {
        guard timer == nil else { return }
        generation = UUID()
        lastCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() { timer?.invalidate(); timer = nil; generation = UUID() }

    func check() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        lastCount = count
        let types = Set(pasteboard.types ?? [])
        guard Self.ignoredTypes.isDisjoint(with: types),
              pasteboard.pasteboardItems?.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) == true else { return }
        let request = generation
        if let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty {
            deliver(request) {
                try files.prefix(100).map { url in
                    let values = try url.resourceValues(forKeys: [.isDirectoryKey])
                    return ClipboardRecord(url: url, kind: FileKind.identify(url, isDirectory: values.isDirectory == true))
                }
            }
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            guard text.utf8.count <= ClipboardAssets.maxTextBytes else { onError("文本超过 1 MB，未记录。"); return }
            deliver(request) {
                let url = try ClipboardAssets.save(Data(text.utf8), extension: "txt")
                return [ClipboardRecord(url: url, kind: .text, text: text, ownedAsset: true)]
            }
        } else if let type = pasteboard.availableType(from: [.png, .tiff]), let data = pasteboard.data(forType: type) {
            guard data.count <= ClipboardAssets.maxImageBytes else { onError("图片超过 64 MB，未记录。"); return }
            deliver(request) {
                guard let png = ClipboardAssets.png(from: data) else {
                    throw NSError(domain: "Suiqu", code: 2, userInfo: [NSLocalizedDescriptionKey: "图片无法解码或超过像素上限，未记录。"])
                }
                let url = try ClipboardAssets.save(png, extension: "png")
                return [ClipboardRecord(url: url, kind: .image, ownedAsset: true)]
            }
        }
    }

    private func deliver(_ request: UUID, work: @escaping () throws -> [ClipboardRecord]) {
        ClipboardAssets.queue.async { [weak self] in
            let result = Result(catching: work)
            DispatchQueue.main.async {
                guard let self, self.generation == request else {
                    if case .success(let records) = result {
                        ClipboardAssets.queue.async { records.forEach { ClipboardAssets.remove($0) } }
                    }
                    return
                }
                switch result {
                case .success(let records): records.forEach(self.onRecord)
                case .failure(let error): self.onError(error.localizedDescription)
                }
            }
        }
    }
}
